// Helper to calculate realistic ISO date from today plus days offset
export function calculateDateString(baseDate: Date, dayOffset: number): string {
  const d = new Date(baseDate);
  d.setDate(d.getDate() + dayOffset);
  return d.toISOString().split('T')[0];
}

// Generate the hydrated dividend stocks relative to reference date
export function getHydratedDividendStocks(referenceDate: Date = new Date()): DividendStock[] {
  return BASE_LARGE_CAP_STOCKS.map((stock) => {
    const exDividendDate = calculateDateString(referenceDate, stock.offsetDays);
    const recordDate = calculateDateString(referenceDate, stock.offsetDays + 1);
    const paymentDate = calculateDateString(referenceDate, stock.offsetDays + 21);
    const declarationDate = calculateDateString(referenceDate, -stock.declarationOffsetDays);

    const isThreeDaysAway = stock.offsetDays === 3;
    const isNewAnnouncement = stock.declarationOffsetDays <= 2;

    return {
      id: `${stock.ticker}-${exDividendDate}`,
      ticker: stock.ticker,
      name: stock.name,
      sector: stock.sector,
      price: stock.price,
      marketCapBillions: stock.marketCapBillions,
      dividendAmount: stock.dividendAmount,
      annualDividend: stock.annualDividend,
      dividendYield: stock.dividendYield,
      payoutRatio: stock.payoutRatio,
      frequency: stock.frequency,
      exDividendDate,
      recordDate,
      paymentDate,
      declarationDate,
      daysUntilExDate: stock.offsetDays,
      isThreeDaysAway,
      isNewAnnouncement,
      growthStreakYears: stock.growthStreakYears,
      safetyScore: stock.safetyScore,
      description: stock.description
    };
  });
}
